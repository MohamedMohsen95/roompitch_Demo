// Prints the built-in catalog as SQL inserts. Made the first seed migration
// (supabase/migrations/*_seed_builtin_catalog.sql); day to day, `npm run catalog:sync` keeps the catalog
// up to date without migrations.
//
//   node scripts/seed-catalog.mjs > supabase/migrations/<timestamp>_seed_builtin_catalog.sql
import { BUILTIN_CATALOG, builtinRows } from "./catalog-rows.mjs";

const q = (v) => v == null ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v)
  : typeof v === "object" ? `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`
  : `'${String(v).replace(/'/g, "''")}'`;

const cols = ["id", "catalog_id", "owner", "kind", "name_en", "name_ar", "ai_description", "category", "w", "d", "h",
  "surface", "price", "unit", "currency", "color", "material", "model_path", "textures", "license", "credits"];
const rows = await builtinRows();

console.log(`-- Built-in catalog, generated by scripts/seed-catalog.mjs (prices are example prices in EGP).
-- owner null = built in: every signed-in user can read it, only the secret key can change it.
insert into public.catalogs (id, owner, name, description) values
  (${q(BUILTIN_CATALOG.id)}, null, ${q(BUILTIN_CATALOG.name)}, ${q(BUILTIN_CATALOG.description)})
on conflict (id) do nothing;

insert into public.catalog_items (${cols.join(", ")}) values
${rows.map(r => "(" + cols.map(c => q(r[c])).join(", ") + ")").join(",\n")}
on conflict (id) do nothing;`);
